#include "obelisk/aot.h"
#include "obelisk/vm.h"
#include <stdlib.h>
#include <string.h>

bool obelisk_aot_transpile_to_c(const ObeliskProgram *program, const ObeliskAotOptions *options, FILE *out_file) {
    if (!program || !out_file) {
        return false;
    }

    const char *fn_name = (options && options->function_name) ? options->function_name : "obelisk_kernel_main";
    size_t tape_size = (options && options->tape_size > 0) ? options->tape_size : OBELISK_DEFAULT_TAPE_SIZE;

    fprintf(out_file, "/* Generated by Obelisk Ahead-Of-Time (AOT) Transpiler */\n");
    fprintf(out_file, "#include <stdint.h>\n");
    fprintf(out_file, "#include <stddef.h>\n");
    fprintf(out_file, "#include <stdio.h>\n");
    fprintf(out_file, "#include <stdlib.h>\n\n");

    fprintf(out_file, "#define TAPE_SIZE %zu\n\n", tape_size);
    fprintf(out_file, "void %s(uint8_t *tape, int (*read_fn)(void), void (*write_fn)(uint8_t)) {\n", fn_name);
    fprintf(out_file, "    size_t ptr = 0;\n\n");

    int indent = 1;
    #define INDENT() for (int _k = 0; _k < indent; ++_k) fprintf(out_file, "    ")

    for (size_t i = 0; i < program->count; ++i) {
        const IrInstruction *in = &program->instructions[i];
        switch (in->opcode) {
            case IR_NOP:
                break;
            case IR_ADD:
                INDENT();
                fprintf(out_file, "tape[ptr] = (uint8_t)(tape[ptr] %+d);\n", in->val);
                break;
            case IR_MOVE:
                INDENT();
                if (in->val > 0) {
                    fprintf(out_file, "ptr += %d;\n", in->val);
                } else {
                    fprintf(out_file, "ptr -= %d;\n", -in->val);
                }
                break;
            case IR_SET:
                INDENT();
                fprintf(out_file, "tape[ptr] = %d;\n", in->val);
                break;
            case IR_READ:
                INDENT();
                fprintf(out_file, "if (read_fn) { int c = read_fn(); if (c >= 0) tape[ptr] = (uint8_t)c; }\n");
                break;
            case IR_WRITE:
                INDENT();
                fprintf(out_file, "if (write_fn) write_fn(tape[ptr]);\n");
                break;
            case IR_JMP_IF_ZERO:
                INDENT();
                fprintf(out_file, "while (tape[ptr]) {\n");
                indent++;
                break;
            case IR_JMP_IF_NZ:
                if (indent > 1) indent--;
                INDENT();
                fprintf(out_file, "}\n");
                break;
            case IR_ADD_MULT:
                INDENT();
                fprintf(out_file, "tape[ptr %+d] = (uint8_t)(tape[ptr %+d] + tape[ptr] * %d); tape[ptr] = 0;\n",
                        in->offset, in->offset, in->factor);
                break;
            case IR_SCAN_FWD:
                INDENT();
                fprintf(out_file, "while (tape[ptr]) ptr += %d;\n", in->val ? in->val : 1);
                break;
            case IR_SCAN_BCK:
                INDENT();
                fprintf(out_file, "while (tape[ptr]) ptr -= %d;\n", in->val ? in->val : 1);
                break;
        }
    }

    fprintf(out_file, "}\n");
    return true;
}

char *obelisk_aot_transpile_to_string(const ObeliskProgram *program, const ObeliskAotOptions *options) {
    char *buf = NULL;
    size_t size = 0;
    FILE *stream = open_memstream(&buf, &size);
    if (!stream) return NULL;

    if (!obelisk_aot_transpile_to_c(program, options, stream)) {
        fclose(stream);
        if (buf) free(buf);
        return NULL;
    }

    fclose(stream);
    return buf;
}
